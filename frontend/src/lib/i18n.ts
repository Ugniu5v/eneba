export const dictionaries = { en, lt } as const;

export type TranslationKey = keyof typeof en;

export function translate(
  language: Language,
  key: string,
  vars?: Record<string, string | number>,
  fallback?: string,
): string {
  const dictionary = dictionaries[language] as Record<string, string>;
  const english = en as Record<string, string>;
  let value = dictionary[key] ?? english[key] ?? fallback ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

export function localeTag(language: Language): string {
  return language === "lt" ? "lt-LT" : "en-IE";
}

export function categoryLabel(language: Language, name: string): string {
  return translate(language, `cat.${name}`, undefined, name);
}

export function genreLabel(language: Language, name: string): string {
  return translate(language, `genre.${name}`, undefined, name);
}

export function regionLabel(language: Language, name: string): string {
  return translate(language, `region.${name}`, undefined, name);
}
